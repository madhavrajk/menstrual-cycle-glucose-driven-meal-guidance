"""Fake participants shaped like mcPHASES, for development, CI, and the public demo.

Output (data/synthetic/, regenerated by `make synthetic`; not real people):
- daily_master_labeled.csv  same columns as Ava's Step 1 output
- glucose.csv, heart_rate.csv, steps.csv, resting_heart_rate.csv, sleep.csv,
  heart_rate_variability_details.csv, computed_temperature.csv
  same columns as the raw mcPHASES tables

Built-in effects (so models have something to find): luteal and menstrual days raise
fatigue, cravings, resting HR, and post-meal glucose spikes, and short sleep raises next-day
spikes and fatigue. Luteal nights also have lower HRV and higher skin temperature.

Sleep timestamps, HRV, and skin temperature are drawn from a second random generator, so
adding them left every earlier synthetic table unchanged.
"""

import argparse

import numpy as np
import pandas as pd

from mealguide import paths

SCALE = ["Not at all", "Very Low/Little", "Low", "Moderate", "High", "Very High"]
MEALS_H = (8, 13, 19)


def _phase(cycle_day: int, length: int) -> str:
    ovulation = length - 14
    if cycle_day < 5:
        return "Menstrual"
    if cycle_day > ovulation:
        return "Luteal"
    if cycle_day >= ovulation - 5:
        return "Fertility"
    return "Follicular"


def _score(rng, latent: float) -> int:
    return int(np.clip(np.round(latent + rng.normal(0, 0.7)), 0, 5))


def generate(n_participants: int = 8, n_days: int = 60, seed: int = 6998) -> dict:
    rng = np.random.default_rng(seed)
    minutes = np.arange(1440)
    daily, glucose, hr, steps, rhr, sleep = [], [], [], [], [], []

    for pid in range(1, n_participants + 1):
        length, offset = rng.integers(26, 33), rng.integers(0, 28)
        hr_offset = rng.normal(0, 5)
        spike_prev = 30.0
        for interval, days in ((2022, range(1, n_days + 1)), (2024, range(905, 925))):
            for day in days:
                cd = (day + offset) % length
                phase = _phase(cd, length)
                luteal, menses = phase == "Luteal", phase == "Menstrual"
                sleep_min = rng.normal(420, 45)
                short_sleep = max(0.0, (420 - sleep_min) / 60)

                row = {"id": pid, "study_interval": interval, "is_weekend": day % 7 in (5, 6),
                       "day_in_study": day, "mira_phase": phase,
                       "lh": rng.lognormal(1.5 + 1.5 * (phase == "Fertility"), 0.4)}
                diary = interval == 2022 and rng.random() > 0.15
                latents = {"fatigue": 1 + 1.2 * luteal + 1.0 * menses + 0.6 * short_sleep,
                           "cramps": 0.3 + 2.5 * menses,
                           "bloating": 1 + 1.0 * luteal + 0.8 * menses,
                           "cravings": 1 + 1.3 * luteal}
                for name, latent in latents.items():
                    s = _score(rng, latent) if diary else None
                    row[name] = SCALE[s] if s is not None else None
                    row[f"{name}_score"] = s
                row["flow_volume"] = "Moderate" if menses and interval == 2022 else None
                row["lh_phase"] = phase if (pid + (day // length)) % 2 == 0 else None
                row["interval_label"] = "Interval 1" if interval == 2022 else "Interval 2"
                daily.append(row)

                keys = (pid, interval, day)
                rhr.append((*keys, 58 + hr_offset + 2.5 * luteal + rng.normal(0, 1.5), 1.0))
                sleep.append((pid, interval, day - 1, day, round(sleep_min),
                              int(np.clip(rng.normal(90, 4), 60, 100)), True))

                worn = rng.random(1440) < rng.uniform(0.75, 0.98)
                bpm = 72 + hr_offset + 3 * luteal + rng.normal(0, 6, 1440)
                hr.append(pd.DataFrame({"id": pid, "study_interval": interval,
                                        "day_in_study": day, "minute": minutes[worn],
                                        "bpm": bpm[worn].round(), "confidence": 2}))
                awake = (minutes >= 7 * 60) & (minutes < 23 * 60)
                steps.append(pd.DataFrame({"id": pid, "study_interval": interval,
                                           "day_in_study": day, "minute": minutes,
                                           "steps": rng.poisson(np.where(awake, 9, 0.1))}))

                if interval == 2022:  # CGM was worn in Interval 1 only
                    spike = (0.5 * spike_prev + 12 + 12 * luteal + 6 * menses
                             + 5 * short_sleep + rng.normal(0, 6))
                    spike_prev = spike
                    t = np.arange(288) * 5
                    g = 90 + 3 * luteal + rng.normal(0, 3, 288)
                    for h in MEALS_H:
                        g += max(spike, 5) * np.exp(-0.5 * ((t - h * 60 - 40) / 35) ** 2)
                    keep = np.ones(288, bool)
                    if rng.random() < 0.1:  # sensor gap day
                        keep = rng.random(288) < 0.4
                    glucose.append(pd.DataFrame({"id": pid, "study_interval": interval,
                                                 "day_in_study": day, "minute": t[keep],
                                                 "glucose_value": g[keep].round()}))

    def with_timestamp(frames):
        df = pd.concat(frames, ignore_index=True)
        m = df.pop("minute")
        df.insert(3, "timestamp", [f"{x // 60:02d}:{x % 60:02d}:00" for x in m])
        return df

    daily_df = pd.DataFrame(daily)
    sleep_df = pd.DataFrame(sleep, columns=[
        "id", "study_interval", "sleep_start_day_in_study", "sleep_end_day_in_study",
        "minutesasleep", "efficiency", "mainsleep"])
    sleep_df, hrv, temp = _overnight(sleep_df, daily_df, seed)

    return {
        "daily_master_labeled": daily_df,
        "glucose": with_timestamp(glucose),
        "heart_rate": with_timestamp(hr),
        "steps": with_timestamp(steps),
        "resting_heart_rate": pd.DataFrame(
            rhr, columns=["id", "study_interval", "day_in_study", "value", "error"]),
        "sleep": sleep_df,
        "heart_rate_variability_details": hrv,
        "computed_temperature": temp,
    }


def _clock(minute: int) -> str:
    return f"{minute // 60:02d}:{minute % 60:02d}:00"


def _overnight(sleep: pd.DataFrame, daily: pd.DataFrame, seed: int):
    """Sleep start/end times, 5-minute HRV during sleep, and nightly skin temperature."""
    rng = np.random.default_rng(seed + 1)
    luteal = daily.set_index(["id", "study_interval", "day_in_study"])["mira_phase"].eq("Luteal")
    person = {pid: (rng.normal(45, 8), rng.normal(34.0, 0.4)) for pid in sleep["id"].unique()}

    starts, ends, hrv_rows, temp_rows = [], [], [], []
    for r in sleep.itertuples(index=False):
        start = r.sleep_start_day_in_study * 1440 + int(np.clip(rng.normal(23 * 60, 40),
                                                                21 * 60 + 30, 25 * 60))
        end = start + int(r.minutesasleep) + 30
        starts.append(start)
        ends.append(end)
        lut = bool(luteal.get((r.id, r.study_interval, r.sleep_end_day_in_study), False))
        base_hrv, base_temp = person[r.id]
        for t in range(start, end, 5):
            hrv_rows.append((r.id, r.study_interval, t // 1440, _clock(t % 1440),
                             max(5.0, round(base_hrv - 6 * lut + rng.normal(0, 8), 1)),
                             0.9))
        temp_rows.append((r.id, r.study_interval, r.sleep_start_day_in_study,
                          _clock(start % 1440), r.sleep_end_day_in_study, _clock(end % 1440),
                          "sleep", round(base_temp + 0.3 * lut + rng.normal(0, 0.15), 2)))

    sleep = sleep.assign(
        sleep_start_timestamp=[_clock(x % 1440) for x in starts],
        sleep_end_timestamp=[_clock(x % 1440) for x in ends],
        sleep_start_day_in_study=[x // 1440 for x in starts],
    )
    hrv = pd.DataFrame(hrv_rows, columns=["id", "study_interval", "day_in_study", "timestamp",
                                          "rmssd", "coverage"])
    temp = pd.DataFrame(temp_rows, columns=[
        "id", "study_interval", "sleep_start_day_in_study", "sleep_start_timestamp",
        "sleep_end_day_in_study", "sleep_end_timestamp", "type", "nightly_temperature"])
    return sleep, hrv, temp


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--participants", type=int, default=8)
    parser.add_argument("--days", type=int, default=60)
    args = parser.parse_args()
    paths.SYNTHETIC.mkdir(parents=True, exist_ok=True)
    for name, df in generate(args.participants, args.days).items():
        df.to_csv(paths.SYNTHETIC / f"{name}.csv", index=False)
        print(f"{name}: {len(df):,} rows")
    print(f"Saved to {paths.SYNTHETIC}")


if __name__ == "__main__":
    main()
